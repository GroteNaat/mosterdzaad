import 'dart:convert';
import 'dart:io';
import 'package:crypto/crypto.dart';

/// Run after `flutter build web --release --no-web-resources-cdn`.
/// Cache all generated assets, including CanvasKit and both font collections.
Future<void> main() async {
  final root = Directory('build/web');
  if (!await File('${root.path}/main.dart.js').exists()) {
    throw StateError('Run flutter build web first.');
  }
  final paths = <String, String>{};
  await for (final file in root.list(recursive: true, followLinks: false)) {
    if (file is! File) continue;
    final path = file.path
        .substring(root.path.length + 1)
        .replaceAll('\\', '/');
    if (path == 'service_worker.js' ||
        path == 'auth.html' ||
        path.startsWith('.') ||
        path.endsWith('.map')) {
      continue;
    }
    paths[path] = sha256.convert(await file.readAsBytes()).toString();
  }
  final names = paths.keys.toList()..sort();
  final version = sha256
      .convert(utf8.encode(jsonEncode({for (final p in names) p: paths[p]})))
      .toString();
  final script =
      '''
// Generated by tool/prepare_pwa.dart. App assets only; never studybooks or OAuth.
const FILES = ${jsonEncode(names)};
const PREFIX = 'mosterdzaad-assets-' + encodeURIComponent(self.registration.scope) + '-';
const CACHE = PREFIX + '$version';
const ROOT = self.registration.scope;
const URLS = new Set(FILES.map(path => new URL(path, ROOT).href));
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    try {
      const cache = await caches.open(CACHE);
      await cache.addAll(FILES.map(path => new Request(new URL(path, ROOT), {cache: 'reload'})));
    } catch (error) {
      await caches.delete(CACHE);
      throw error;
    }
  })());
  // Deliberately no skipWaiting: do not replace code underneath unsaved edits.
});
self.addEventListener('activate', event => event.waitUntil((async () => {
  for (const name of await caches.keys()) {
    if (name.startsWith(PREFIX) && name !== CACHE) await caches.delete(name);
  }
  await self.clients.claim();
})()));
self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== new URL(ROOT).origin || !url.href.startsWith(ROOT)) return;
  // Exact allowlist: auth.html, Dropbox and arbitrary downloads bypass the cache.
  const key = url.href === ROOT ? new URL('index.html', ROOT).href : url.href;
  if (!URLS.has(key)) return;
  event.respondWith((async () => (await (await caches.open(CACHE)).match(key)) || fetch(request))());
});
''';
  await File('${root.path}/service_worker.js').writeAsString(script);
  stdout.writeln(
    'PWA: ${names.length} offline assets, version ${version.substring(0, 12)}',
  );
}
